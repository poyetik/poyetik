// The seeded pseudo-random generator the property tests share, so that none keeps its own copy.

/** A seeded pseudo-random generator (mulberry32): the same sequence for the same seed, on every run, each number in [0, 1). */
export function random(seed: number): () => number {
  let state = seed;
  return () => {
    state = (state + 0x6d2b79f5) | 0;
    let mixed = Math.imul(state ^ (state >>> 15), 1 | state);
    mixed = (mixed + Math.imul(mixed ^ (mixed >>> 7), 61 | mixed)) ^ mixed;
    return ((mixed ^ (mixed >>> 14)) >>> 0) / 4_294_967_296;
  };
}
